"""
app/core/assistant.py
─────────────────────
BOB assistant core.

Responsibilities:
  • Manage conversation history for the current session.
  • Receive user messages and return assistant replies.
  • Run the agentic tool-calling loop when a ToolRegistry is provided.
  • Delegate LLM calls to an injected LLM client (dependency-injection,
    no hard import of requests or Ollama specifics here).

The system prompt can be customised via the BOB_SYSTEM_PROMPT env var
(JARVIS_SYSTEM_PROMPT is also accepted for backwards compatibility).

Tool calling flow (when registry is provided and LLM supports it)
─────────────────────────────────────────────────────────────────
  User message
      │
      ▼
  LLM (with tools list)
      │
      ├─ tool_calls present? ──► execute tool via registry ──► append result ──► loop
      │
      └─ text content only? ──► return as assistant reply
"""

from __future__ import annotations

import json
import logging
import os
import re
from typing import Any, Collection, Dict, List, Optional, Protocol, TYPE_CHECKING

if TYPE_CHECKING:
    from app.tools.registry import ToolRegistry

from app.llm.nvidia_client import (
    NvidiaClient as _NvidiaClient,
    NvidiaConnectionError as _NvidiaConnectionError,
    NvidiaRateLimitError as _NvidiaRateLimitError,
)

logger = logging.getLogger(__name__)

# ── Maximum tool-call iterations per user turn ────────────────────────────────
MAX_TOOL_ITERATIONS: int = 6


# ─── LLM client protocol (structural subtyping) ───────────────────────────────
# Any object with chat() -> str is accepted.
# chat_with_tools() is OPTIONAL — checked via hasattr at runtime.
# This keeps the assistant decoupled from OllamaClient specifically.

class LLMClient(Protocol):
    """Minimal interface expected from any LLM backend."""

    def chat(self, messages: List[Dict[str, str]], **kwargs) -> str:
        ...  # pragma: no cover


class RequestRouter(Protocol):
    """
    Optional fast pre-classifier for new user requests (e.g. LayaRouter).

    route() returns an object whose ``hint`` attribute is a routing hint string
    for the LLM, or None for "no hint". The router never executes tools.
    """

    def route(self, text: str) -> Any:
        ...  # pragma: no cover


# ─── Default system prompt ────────────────────────────────────────────────────

_DEFAULT_SYSTEM_PROMPT = (
    "You are BOB, a helpful, concise, and honest AI assistant running on the user's computer. "
    "Your replies are generated by the configured language model provider, which may be "
    "a local model (Ollama) or a cloud model (NVIDIA NIM); do not claim to run entirely "
    "locally or entirely in the cloud unless you know which provider is in use. "
    "Be direct and clear. "
    "If you do not know something, say so honestly rather than guessing. "
    "When a tool is available and relevant, use it to get accurate information "
    "rather than guessing."
)


# ─── Assistant ────────────────────────────────────────────────────────────────

class JarvisAssistant:
    """
    Core BOB assistant.

    Usage (plain conversation)::

        from app.llm.ollama_client import OllamaClient
        from app.core.assistant import JarvisAssistant

        client = OllamaClient()
        bob = JarvisAssistant(llm_client=client)
        reply = bob.chat("Hello!")

    Usage (with tools)::

        from app.tools.registry import build_default_registry

        registry = build_default_registry()
        bob = JarvisAssistant(llm_client=client, tool_registry=registry)
        reply = bob.chat("What is my RAM usage?")
        # → BOB calls get_system_info, then answers with real data

    The assistant keeps the full conversation history in memory for the
    duration of the process.  Tool call turns (assistant tool_calls + tool
    results) are stored in history so the LLM has full context.
    """

    def __init__(
        self,
        llm_client: LLMClient,
        *,
        system_prompt: Optional[str] = None,
        tool_registry: Optional["ToolRegistry"] = None,
        router: Optional[RequestRouter] = None,
        fallback_llm: Optional[LLMClient] = None,
    ) -> None:
        """
        :param llm_client:    Any object that satisfies the LLMClient protocol.
        :param system_prompt: Override the built-in system prompt.
        :param tool_registry: Optional ToolRegistry.  When provided and the LLM
                              client supports chat_with_tools(), tool calling is
                              enabled automatically.
        :param router:        Optional RequestRouter.  Each new user message is
                              routed once; the resulting hint is shown to the LLM
                              for that turn only.  The LLM and ToolRegistry stay
                              authoritative; router failures mean "no hint".
        :param fallback_llm:  Optional fallback LLM client used when the primary
                              raises NvidiaConnectionError or NvidiaRateLimitError.
                              If it exposes is_available(), that is checked first.
        """
        self._llm = llm_client
        self._fallback_llm = fallback_llm
        self._tool_registry = tool_registry
        self._router = router
        self._last_route: Any = None

        resolved_prompt = (
            system_prompt
            or os.environ.get("BOB_SYSTEM_PROMPT")
            or os.environ.get("JARVIS_SYSTEM_PROMPT")
            or _DEFAULT_SYSTEM_PROMPT
        )
        self._system_prompt: str = resolved_prompt

        self._history: List[Dict[str, Any]] = [
            {"role": "system", "content": self._system_prompt}
        ]

        logger.debug(
            "JarvisAssistant initialised. tools=%s",
            tool_registry.list_tools() if tool_registry else "none",
        )

    # ── Public API ────────────────────────────────────────────────────────────

    def chat(self, user_message: str) -> str:
        """
        Send a user message, get the assistant reply, and update history.

        If a ToolRegistry is attached and the LLM client supports
        chat_with_tools(), the agentic tool loop runs automatically.

        :param user_message: The raw text typed by the user.
        :returns:            The assistant's text reply.
        :raises:             Re-raises any exception from the LLM client.
        """
        if not user_message or not user_message.strip():
            return "(Please enter a message.)"

        self._history.append({"role": "user", "content": user_message.strip()})
        turn_start = len(self._history) - 1
        hint = self._route_hint(user_message.strip())
        logger.debug("Sending %d messages to LLM …", len(self._history))

        # Laya model routing: use the per-request model selected by the router
        # when the active LLM backend is NvidiaClient.  For other backends (e.g.
        # Ollama) the selected_model would be an NVIDIA model ID that the backend
        # cannot use, so it is suppressed.
        selected_model: Optional[str] = (
            getattr(self._last_route, "selected_model", None)
            if isinstance(self._llm, _NvidiaClient) else None
        )

        # Decide whether to use the agentic tool loop
        use_tools = (
            self._tool_registry is not None
            and bool(self._tool_registry.list_tools())
            and hasattr(self._llm, "chat_with_tools")
        )

        try:
            if use_tools:
                reply = self._agentic_loop(hint=hint, turn_start=turn_start, model=selected_model)
            else:
                reply = self._llm.chat(self._llm_messages(hint, turn_start), model=selected_model)
        except (_NvidiaConnectionError, _NvidiaRateLimitError) as _nvidia_exc:
            # Transient NVIDIA failure (timeout or rate-limit). Pop the user
            # message that was added optimistically — _agentic_loop already
            # restored the snapshot, so history is now clean except for that.
            self._history.pop()

            if self._fallback_llm is None:
                raise

            # Verify the fallback service is reachable before committing.
            if hasattr(self._fallback_llm, "is_available") and not self._fallback_llm.is_available():
                raise _nvidia_exc  # surface original NVIDIA error

            # Re-add user message and retry through the fallback LLM.
            self._history.append({"role": "user", "content": user_message.strip()})
            fallback_use_tools = (
                self._tool_registry is not None
                and bool(self._tool_registry.list_tools())
                and hasattr(self._fallback_llm, "chat_with_tools")
            )
            logger.warning(
                "Primary LLM failed (%s); retrying via fallback LLM.",
                type(_nvidia_exc).__name__,
            )
            try:
                if fallback_use_tools:
                    reply = self._agentic_loop(
                        hint=hint, turn_start=turn_start, model=None,
                        _llm_override=self._fallback_llm,
                    )
                else:
                    reply = self._fallback_llm.chat(
                        self._llm_messages(hint, turn_start), model=None
                    )
            except Exception:
                # Fallback also failed — restore history and surface the
                # original NVIDIA error so the caller knows the root cause.
                self._history.pop()
                raise _nvidia_exc
        except Exception:
            # On LLM/tool failure, remove the user message so history stays
            # consistent (user message was added optimistically above).
            self._history.pop()
            raise

        self._history.append({"role": "assistant", "content": reply})
        return reply

    def reset(self) -> None:
        """Clear conversation history (system prompt is preserved)."""
        self._history = [{"role": "system", "content": self._system_prompt}]
        logger.debug("Conversation history reset.")

    @property
    def history(self) -> List[Dict[str, Any]]:
        """Read-only snapshot of the current conversation history."""
        return list(self._history)

    @property
    def system_prompt(self) -> str:
        """The active system prompt."""
        return self._system_prompt

    @property
    def tool_registry(self) -> Optional["ToolRegistry"]:
        """The attached ToolRegistry, or None."""
        return self._tool_registry

    @property
    def router(self) -> Optional[RequestRouter]:
        """The attached RequestRouter, or None."""
        return self._router

    @property
    def last_route(self) -> Any:
        """The router's decision for the most recent user message (or None)."""
        return self._last_route

    # ── Request routing ───────────────────────────────────────────────────────

    def _route_hint(self, user_message: str) -> Optional[str]:
        """Route the new user message once; return its LLM hint or None."""
        self._last_route = None
        if self._router is None:
            return None
        try:
            decision = self._router.route(user_message)
        except Exception as exc:  # noqa: BLE001 – a router must never break chat
            logger.warning("Request router failed; continuing without a hint: %s", exc)
            return None
        self._last_route = decision
        logger.info(
            "Route: %s (%.0f ms)",
            getattr(decision, "category", "?"), getattr(decision, "latency_ms", 0.0) or 0.0,
        )
        hint = getattr(decision, "hint", None)
        return hint if isinstance(hint, str) and hint.strip() else None

    def _llm_messages(self, hint: Optional[str], turn_start: Optional[int]) -> List[Dict[str, Any]]:
        """
        Messages to send to the LLM for the current turn.

        Without a hint this is exactly self._history.  With one, the hint is
        inserted as a system message just before the current user message.
        It is never stored in history, so hints from earlier turns cannot leak.
        """
        if not hint or turn_start is None:
            return self._history
        messages = list(self._history)
        messages.insert(turn_start, {"role": "system", "content": hint})
        return messages

    # ── Agentic tool loop ─────────────────────────────────────────────────────

    def _agentic_loop(
        self,
        hint: Optional[str] = None,
        turn_start: Optional[int] = None,
        model: Optional[str] = None,
        *,
        _llm_override: Optional[Any] = None,
    ) -> str:
        """
        Run the tool-calling loop until the LLM gives a text answer or we hit
        the iteration limit.

        History management:
          • Intermediate assistant-with-tool_calls messages are appended to
            self._history so the LLM has full context on the next iteration.
          • Tool result messages (role="tool") are appended after each execution.
          • The FINAL text reply is NOT appended here; chat() does that.
          • If an exception escapes, history is restored to its pre-loop state
            (but the user message, added by chat(), is preserved).
        """
        assert self._tool_registry is not None  # guarded by caller
        tools = self._tool_registry.get_tool_schemas()
        _llm = _llm_override if _llm_override is not None else self._llm

        # Snapshot history at the start of the loop so we can restore on error
        # (the user message is already in self._history at this point)
        snapshot: List[Dict[str, Any]] = list(self._history)

        try:
            for iteration in range(MAX_TOOL_ITERATIONS):
                message: Dict[str, Any] = _llm.chat_with_tools(  # type: ignore[attr-defined]
                    self._llm_messages(hint, turn_start), tools, model=model
                )

                content: str = message.get("content") or ""
                tool_calls: List[Dict[str, Any]] = message.get("tool_calls") or []

                # ── Text-mode fallback ────────────────────────────────────────
                # Some model/Ollama combinations emit tool calls as plain JSON
                # text instead of the structured tool_calls field.  Detect and
                # parse that pattern so the loop works regardless.
                if not tool_calls and content:
                    known_tools = set(self._tool_registry.list_tools()) if self._tool_registry else None
                    tool_calls = self._parse_text_tool_call(content, known_tools=known_tools) or []

                # Filter out empty or pseudo-tool calls (e.g. model outputting name="None" / "null")
                if tool_calls:
                    valid_tool_calls: List[Dict[str, Any]] = []
                    for tc in tool_calls:
                        fn_name = str(tc.get("function", {}).get("name", "")).strip()
                        if fn_name and fn_name.lower() not in ("none", "null", "no_tool", "undefined"):
                            valid_tool_calls.append(tc)
                    tool_calls = valid_tool_calls

                if not tool_calls:
                    # LLM produced a text answer — done
                    logger.debug("Agentic loop finished after %d iteration(s).", iteration + 1)
                    return content

                # ── The LLM wants to call one or more tools ───────────────────
                logger.debug(
                    "Iteration %d: LLM requested %d tool call(s).", iteration + 1, len(tool_calls)
                )

                # Append the assistant message (with tool_calls) to history.
                # In standard tool-calling format, content is empty when tool_calls
                # are present so the LLM is not confused by its own JSON in next turn.
                stored_content = "" if tool_calls else content
                self._history.append(
                    {"role": "assistant", "content": stored_content, "tool_calls": tool_calls}
                )

                # Execute each tool in order and append its result
                for tc in tool_calls:
                    func_info = tc.get("function", {})
                    tool_name: str = func_info.get("name", "")
                    raw_args: Any = func_info.get("arguments", {})

                    # Ollama may return arguments as a dict or a JSON string
                    if isinstance(raw_args, str):
                        try:
                            tool_args: Dict[str, Any] = json.loads(raw_args)
                        except json.JSONDecodeError:
                            tool_args = {}
                    else:
                        tool_args = raw_args if isinstance(raw_args, dict) else {}

                    logger.info("Calling tool %r with args: %r", tool_name, tool_args)
                    result: Dict[str, Any] = self._tool_registry.execute(tool_name, tool_args)

                    self._history.append(
                        {"role": "tool", "content": json.dumps(result, default=str)}
                    )

            # Max iterations reached without a text answer
            logger.warning("Agentic loop hit MAX_TOOL_ITERATIONS (%d).", MAX_TOOL_ITERATIONS)
            return (
                "I reached the maximum number of reasoning steps. "
                "Please try rephrasing your request."
            )

        except Exception:
            # Restore history to the snapshot so partial tool turns don't corrupt context
            self._history = snapshot
            raise

    # ── Text-mode tool call detection ──────────────────────────────────────────

    @staticmethod
    def _parse_text_tool_call(
        content: str, known_tools: Optional[Collection[str]] = None
    ) -> List[Dict[str, Any]]:
        """
        Attempt to parse a tool call from plain-text or markdown-formatted content.

        Handles multiple formatting variations emitted by local models:
          - Raw JSON: {"name": "...", "arguments": {...}}
          - Markdown code fences: ```json ... ``` or ``` ... ```
          - XML-style tags: <tool_call> ... </tool_call>
          - JSON embedded within surrounding introductory/concluding text
          - Direct JSON list: [{"name": "...", "arguments": {...}}]
          - Wrapped tool_calls: {"tool_calls": [...]}
          - OpenAI style: {"type": "function", "function": {"name": ...}}
          - 'parameters' key as alias for 'arguments'
          - Serialized JSON string arguments: "arguments": "{\"key\": \"val\"}"
          - Known tools with omitted arguments

        Returns a list of tool-call dicts in the standard Ollama format, or []
        if the content does not contain a valid tool call.
        """
        if not content or not content.strip():
            return []

        text = content.strip()

        # 1. If wrapped in markdown code fence(s), extract the inner content
        fence_pattern = r"```(?:json|tool_call|tools)?\s*([\s\S]*?)\s*```"
        fence_matches = re.findall(fence_pattern, text, re.IGNORECASE)
        candidates: List[str] = []
        if fence_matches:
            for m in fence_matches:
                candidates.append(m.strip())

        # 2. If wrapped in XML-style tags like <tool_call>...</tool_call>
        tag_pattern = r"<tool_call>\s*([\s\S]*?)\s*</tool_call>"
        tag_matches = re.findall(tag_pattern, text, re.IGNORECASE)
        if tag_matches:
            for m in tag_matches:
                candidates.append(m.strip())

        # 3. Always test the full stripped text
        candidates.append(text)

        # 4. If text contains a JSON object or array somewhere inside surrounding prose,
        # extract the substring between first '{' and last '}', or first '[' and last ']'
        first_brace = text.find("{")
        last_brace = text.rfind("}")
        if first_brace != -1 and last_brace > first_brace:
            candidates.append(text[first_brace : last_brace + 1].strip())

        first_bracket = text.find("[")
        last_bracket = text.rfind("]")
        if first_bracket != -1 and last_bracket > first_bracket:
            candidates.append(text[first_bracket : last_bracket + 1].strip())

        def _normalize_args(raw_args: Any) -> Optional[Dict[str, Any]]:
            """Ensure arguments is a dictionary; decode stringified JSON if needed."""
            if raw_args is None:
                return {}
            if isinstance(raw_args, dict):
                return raw_args
            if isinstance(raw_args, str):
                raw_args = raw_args.strip()
                if not raw_args or raw_args in ("{}", "null"):
                    return {}
                try:
                    parsed_args = json.loads(raw_args)
                    if isinstance(parsed_args, dict):
                        return parsed_args
                    return None
                except json.JSONDecodeError:
                    return None
            return None

        def _normalize_tool_call(item: Any) -> Optional[Dict[str, Any]]:
            """Convert arbitrary parsed dictionary to standard Ollama tool_call structure."""
            if not isinstance(item, dict):
                return None

            # Case A: nested function dictionary (e.g. OpenAI / Ollama standard format)
            if "function" in item and isinstance(item["function"], dict):
                fn = item["function"]
                if "name" in fn and isinstance(fn["name"], str) and fn["name"].strip():
                    tool_name = fn["name"].strip()
                    if tool_name.lower() in ("none", "null", "no_tool", "undefined"):
                        return None
                    if known_tools is not None and tool_name not in known_tools:
                        return None
                    clean_args = _normalize_args(fn.get("arguments"))
                    if clean_args is not None:
                        return {"function": {"name": tool_name, "arguments": clean_args}}

            # Case B: top-level name with arguments or parameters
            if "name" in item and isinstance(item["name"], str) and item["name"].strip():
                tool_name = item["name"].strip()
                if tool_name.lower() in ("none", "null", "no_tool", "undefined"):
                    return None
                if known_tools is not None and tool_name not in known_tools:
                    return None
                has_args = "arguments" in item
                has_params = "parameters" in item

                # If arguments/parameters key is absent, only accept if it matches a known registered tool
                if not has_args and not has_params:
                    if known_tools and tool_name in known_tools:
                        return {"function": {"name": tool_name, "arguments": {}}}
                    return None

                raw_args = item.get("arguments") if has_args else item.get("parameters")
                clean_args = _normalize_args(raw_args)
                if clean_args is not None:
                    return {"function": {"name": tool_name, "arguments": clean_args}}

            return None

        # Try parsing each extracted candidate in priority order
        seen_candidates = set()
        for cand in candidates:
            if not cand or cand in seen_candidates:
                continue
            seen_candidates.add(cand)

            try:
                parsed = json.loads(cand)
            except (json.JSONDecodeError, TypeError, ValueError):
                continue

            # Case 1: Parsed is a direct list of tool calls
            if isinstance(parsed, list):
                results = []
                for elem in parsed:
                    norm = _normalize_tool_call(elem)
                    if norm:
                        results.append(norm)
                if results:
                    return results

            # Case 2: Parsed is a dictionary
            if isinstance(parsed, dict):
                # Check tool_calls list wrapper
                if "tool_calls" in parsed and isinstance(parsed["tool_calls"], list):
                    results = []
                    for elem in parsed["tool_calls"]:
                        norm = _normalize_tool_call(elem)
                        if norm:
                            results.append(norm)
                    if results:
                        return results

                # Check single tool call
                norm = _normalize_tool_call(parsed)
                if norm:
                    return [norm]

        return []

    def __repr__(self) -> str:  # pragma: no cover
        return (
            f"JarvisAssistant(turns={len(self._history) - 1}, "
            f"tools={self._tool_registry.list_tools() if self._tool_registry else []!r})"
        )


BobAssistant = JarvisAssistant
